import {GameState, MetricImpact} from './types';

export interface TreasuryLine {
  id: string;
  label: string;
  detail: string;
  amount: number;
  kind: 'revenue' | 'expense';
}

export interface TreasuryForecast {
  revenues: TreasuryLine[];
  expenses: TreasuryLine[];
  totalRevenue: number;
  totalExpenses: number;
  net: number;
  projectedBalance: number;
  outlook: 'surplus' | 'balanced' | 'deficit';
}

/**
 * Explains the recurring cash flows that will settle after the next decision.
 * Action costs and effects are deliberately excluded because the player has not
 * chosen them yet.
 */
export function projectTreasury(state: GameState): TreasuryForecast {
  const lines: TreasuryLine[] = [];
  const add = (id: string, label: string, detail: string, amount: number) => {
    if (!amount) return;
    lines.push({id, label, detail, amount, kind: amount > 0 ? 'revenue' : 'expense'});
  };

  const domesticBalance = Math.round((state.economy.growth - 4000) / 7);
  add(
    'domestic-balance',
    domesticBalance >= 0 ? 'Domestic tax base' : 'Economic support burden',
    domesticBalance >= 0 ? 'Revenue generated by productive growth.' : 'Weak growth requires automatic support and lost revenue.',
    domesticBalance,
  );

  if (state.world) {
    const owned = state.world.territories.filter(territory => territory.ownerId === state.world!.playerNationId);
    add(
      'territory-revenue',
      'Territory revenue',
      `${owned.length} controlled territories contribute taxes, resources, and customs duties.`,
      owned.reduce((sum, territory) => sum + Math.round(territory.wealth / 65), 0),
    );

    for (const deal of state.world.deals) {
      const nation = state.world.nations.find(item => item.id === deal.nationId);
      if (nation?.atWar) {
        add(
          `disrupted-${deal.id}`,
          `Disrupted ${deal.kind} agreement`,
          `Conflict with ${nation.name} will terminate the agreement and impose an emergency loss.`,
          -140,
        );
      } else {
        add(
          deal.id,
          deal.kind === 'trade' ? 'Trade corridor income' : 'Business consortium income',
          `${nation?.name ?? 'Foreign partner'} · ${deal.yearsRemaining} years remain · ${Math.round(deal.breachRisk * 100)}% annual breach risk.`,
          deal.annualIncome,
        );
      }
    }

    const activeWars = state.world.wars.filter(war => !war.targetNationId).length;
    add(
      'war-upkeep',
      'Active-war upkeep',
      `${activeWars} player war${activeWars === 1 ? '' : 's'} require logistics, replacements, and field pay.`,
      activeWars * -260,
    );
  }

  for (const effect of state.scheduledEffects.filter(item => item.dueTurn <= state.turn + 1)) {
    const treasuryChange = effect.changes
      .filter(change => change.path === 'treasury')
      .reduce((sum, change) => sum + change.amount, 0);
    add(
      `scheduled-${effect.id}`,
      effect.source,
      `Committed consequence due ${effect.dueTurn <= state.turn ? 'now' : 'next period'}.`,
      treasuryChange,
    );
  }

  const revenues = lines.filter(line => line.amount > 0);
  const expenses = lines.filter(line => line.amount < 0);
  const totalRevenue = revenues.reduce((sum, line) => sum + line.amount, 0);
  const totalExpenses = Math.abs(expenses.reduce((sum, line) => sum + line.amount, 0));
  const net = totalRevenue - totalExpenses;
  return {
    revenues,
    expenses,
    totalRevenue,
    totalExpenses,
    net,
    projectedBalance: Math.max(0, state.treasury + net),
    outlook: net > 100 ? 'surplus' : net < -100 ? 'deficit' : 'balanced',
  };
}

export function latestTreasuryImpacts(state: GameState): Array<MetricImpact & {source: string}> {
  return (state.lastTurnReport?.sections ?? []).flatMap(section => section.impacts
    .filter(impact => impact.path === 'treasury')
    .map(impact => ({...impact, source: section.title})));
}
